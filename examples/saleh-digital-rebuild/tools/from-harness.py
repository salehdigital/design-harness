#!/usr/bin/env python3
"""Write the rebuild's JS modules straight out of the harness records.

Every module here is a verbatim code block from harnesses/saleh-digital (the record
names the source file with a 'Source: `site/js/NAME`, whole file' line). Nothing is
written by hand except the few import lines patched at the bottom, which point the
modules at each other inside this folder. Run from anywhere:

    python3 examples/saleh-digital-rebuild/tools/from-harness.py
"""
import os, re
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..'))
H = os.path.normpath(os.path.join(ROOT, '..', '..', 'harnesses', 'saleh-digital'))
OUT = os.path.join(ROOT, 'js')

def block(record, source, lines=None):
    s = open(os.path.join(H, record), encoding='utf-8').read()
    tag = f'Source: `site/js/{source}`, ' + (f'lines {lines[0]} to {lines[1]}' if lines else 'whole file')
    i = s.index(tag)
    m = re.compile(r'```js\n(.*?)\n```', re.S).search(s, i)
    return m.group(1) + '\n'

def put(name, text):
    os.makedirs(OUT, exist_ok=True)
    open(os.path.join(OUT, name), 'w', encoding='utf-8').write(
        f'// Generated by tools/from-harness.py from harnesses/saleh-digital. Do not edit.\n{text}')
    print('wrote js/' + name)

put('state.js', block('foundations/motion/motion.md', 'state.js'))
put('tokens.js', block('foundations/motion/motion.md', 'tokens.js'))
put('theme.js', block('foundations/themes.md', 'theme.js'))
put('audio.js', block('foundations/sound/sound.md', 'audio.js'))
put('haptics.js', block('foundations/sound/sound.md', 'haptics.js'))
put('mcp.js', block('templates/settings.md', 'mcp.js'))
# streamIn and its helpers (resolve.js lines 95 to 195), with the imports they use
put('stream.js', "import { bus, params, reducedMotion } from './state.js';\nimport { MOTION } from './tokens.js';\n"
    + block('foundations/motion/streaming.md', 'resolve.js', (95, 195)))
# Settings (Theme, Sound, MCP pages): the site's module, its imports pointed here
st = block('templates/settings.md', 'settings.js')
st = st.replace("import { CONTACT_EMAIL } from './content.js';", "const CONTACT_EMAIL = '';")
st = st.replace("from './resolve.js';", "from './stream.js';")
put('settings.js', st)
